import type { Card, CardType, Element, EquipSlot, HeroData, Suit } from './types';

let seq = 0;

function card(
  name: string,
  suit: Suit,
  rank: number,
  type: CardType,
  equipSlot?: EquipSlot,
  range?: number,
  element?: Element,
): Card {
  seq += 1;
  return { id: `c${seq}`, name, suit, rank, type, equipSlot, range, element };
}

function cards(name: string, suit: Suit, ranks: number[]): Card[] {
  return ranks.map((r) => card(name, suit, r, 'basic'));
}

function tricks(name: string, suit: Suit, ranks: number[], type: CardType = 'trick'): Card[] {
  return ranks.map((r) => card(name, suit, r, type));
}

function equip(name: string, suit: Suit, rank: number, slot: EquipSlot, range?: number): Card {
  return card(name, suit, rank, 'equip', slot, range);
}

